"""Decompilation inventory: every function a coverage set hit, with module, address, size and a subsystem group.

Inputs (all generated by earlier steps, nothing read from Ghidra here):
  project/generated/<module>/bf3_functions.tsv   codegen function list (address, size, blocks, name)
  logs/decomp/xrefs_<module>.json                 calls / tail calls / lis-built constants per function (xrefs.py)
  logs/decomp/reflection.json                     Frostbite type records (reflection.py)
  <typeinfo.bin>                                  the typeinfo section from a running game (coverage_session.py)
  logs/coverage/<run>/*.tsv                       hit sets (module<TAB>0xADDR)

Classification, strongest signal first:
  1. class: the function is a slot of a vtable whose getType() names a Frostbite class (TypeInfo -> record -> name),
     a reflected class's create function, or stores a named vtable (constructor/destructor); the class name maps to
     a group (CLASS_RULES)
  2. strings the function builds the address of (STRING_RULES; e.g. "hkp..." -> havok, "GFx" -> ui)
  3. anchors: address ranges established by earlier work (ANCHORS: Lua, CRT, Scaleform, Havok, job system ...)
  4. address neighbours: static libraries are linked as contiguous blocks, so an unlabeled function takes the label
     its nearest labeled neighbours agree on
  5. call graph: the majority label of its callers and callees
Each function gets the group, the signal that decided it ("class:ServerSoldierEntity", "str:...", "addr", "calls")
and a confidence (high/medium/low).

Usage: inventory.py <coverage dir or tsv>... [--typeinfo logs/coverage/<run>/typeinfo.bin] [--out docs/decomp]
"""
