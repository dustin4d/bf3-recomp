def load_hits(paths):
    """{(module, addr): set of phase names}"""
    hits = collections.defaultdict(set)
    files = []
    for p in paths:
        files += sorted(glob.glob(os.path.join(p, "*.tsv"))) if os.path.isdir(p) else [p]
    for f in files:
        run = os.path.basename(os.path.dirname(f))
        phase = re.sub(r"^\d+-", "", os.path.splitext(os.path.basename(f))[0])
        for line in open(f):
            mod, a = line.split()
            hits[(mod, int(a, 16))].add(f"{run}:{phase}")
    return hits


def gettype_target(f):
    """getType() stub "lis r11,hi; addi r3,r11,lo; blr" -> the TypeInfo object it returns."""
    try:
        i0, i1, i2 = u32(f), u32(f + 4), u32(f + 8)
    except struct.error:
        return None
    if i0 >> 26 == 15 and i1 >> 26 == 14 and i2 == 0x4E800020 and ((i1 >> 21) & 31) == 3:
        lo = i1 & 0xFFFF
        lo = lo - 0x10000 if lo & 0x8000 else lo
        return (((i0 & 0xFFFF) << 16) + lo) & 0xFFFFFFFF
    return None


def type_names(typeinfo_bin):
    """TypeInfo object address -> class name, from the runtime typeinfo section (object +0 -> record, +0 name)."""
    names = {}
    if not typeinfo_bin or not os.path.exists(typeinfo_bin):
        return names
    data = open(typeinfo_bin, "rb").read()
    for off in range(0, len(data) - 4, 4):
        rec = struct.unpack_from(">I", data, off)[0]
        if TYPEINFO[0] <= rec < TYPEINFO[1]:
            n = cstr(u32(rec))
            if n:
                names[TYPEINFO[0] + off] = n
    return names


def find_vtables(starts, code_refs, tnames):
    """BF.Main vtables in .rdata: runs of function pointers, split where code builds the address of a position (a
    constructor storing the vtable). Returns [(vtable addr, [slot functions], class name or None)]."""
    out = []
    a = RDATA[0]
    while a < RDATA[1]:
        if u32(a) not in starts:
            a += 4
            continue
        b = a
        while b < RDATA[1] and u32(b) in starts:
            b += 4
        cuts = [p for p in range(a, b, 4) if p in code_refs or gettype_target(u32(p)) in tnames] or [a]
        if cuts[0] != a:
            cuts.insert(0, a)
        cuts.append(b)
        for s, e in zip(cuts, cuts[1:]):
            slots = [u32(p) for p in range(s, e, 4)]
            if len(slots) >= 2 or s in code_refs:
                out.append((s, slots, tnames.get(gettype_target(slots[0]))))
        a = b
    return out


def rule_group(rules, text):
    for g, rx in rules:
        if re.search(rx, text):
            return g
    return None


def classify(funcs, xrefs, tnames):
    main_starts = {a for (m, a) in funcs if m == "BF.Main"}
    code_refs = set()
    for (m, a), v in xrefs.items():
        if m == "BF.Main":
            code_refs.update(r for r in v["refs"] if RDATA[0] <= r < RDATA[1])
    vtables = find_vtables(main_starts, code_refs, tnames)

    label = {}  # key -> (group, why, confidence)
    # 1. classes. A function shared by several vtables (inherited, not overridden) belongs to the most basic class:
    # take the vote of all its classes and prefer frostbite-core when they disagree.
    votes = collections.defaultdict(collections.Counter)
    owner = collections.defaultdict(set)
    for vt, slots, cls in vtables:
        if not cls:
            continue
        g = rule_group(CLASS_RULES, cls)
        for f in slots:
            votes[("BF.Main", f)][g] += 1
            owner[("BF.Main", f)].add(cls)
    # a reflected class's create function (type record +0x14, reflection.py) belongs to that class
    refl = os.path.join(ROOT, "logs", "decomp", "reflection.json")
    if os.path.exists(refl):
        for r in json.load(open(refl)):
            if r.get("create") and ("BF.Main", r["create"]) in funcs:
                k = ("BF.Main", r["create"])
                votes[k][rule_group(CLASS_RULES, r["name"])] += 1
                owner[k].add(r["name"])
    for k, c in votes.items():
        (g, n), = c.most_common(1)
        if len(c) > 1 and c.most_common(2)[1][1] == n:
            g = "frostbite-core"
        cls = sorted(owner[k], key=len)[0]
        label[k] = (g, f"class:{cls}" + (f"+{len(owner[k]) - 1}" if len(owner[k]) > 1 else ""), "high")

    # 1b. constructors / destructors: functions that store a named class's vtable address
    named_vt = {vt: cls for vt, slots, cls in vtables if cls}
    for k, v in xrefs.items():
        if k in label or k[0] != "BF.Main":
            continue
        classes = sorted({named_vt[r] for r in v["refs"] if r in named_vt}, key=len)
        if classes:
            g = collections.Counter(rule_group(CLASS_RULES, c) for c in classes).most_common(1)[0][0]
            label[k] = (g, f"vtable:{classes[0]}" + (f"+{len(classes) - 1}" if len(classes) > 1 else ""), "high")

    # 2. strings
    for k, v in xrefs.items():
        if k in label or k[0] != "BF.Main":
            continue
        c = collections.Counter()
        ex = {}
        for r in v["refs"]:
            if not (MAIN_BASE <= r < 0x84260000):
                continue
            s = cstr(r)
            if s and len(s) >= 4:
                g = rule_group(STRING_RULES, s)
                if g:
                    c[g] += 1
                    ex.setdefault(g, s)
        if c:
            g, n = c.most_common(1)[0]
            label[k] = (g, f"str:{ex[g][:40]}", "high" if n >= 2 or len(c) == 1 else "medium")

    # 3. anchors: libraries override, subsystem blocks fill what classes and strings left open
    for k in funcs:
        if k[0] == "BF.Main":
            for g, lo, hi, why in LIBRARY_ANCHORS:
                if lo <= k[1] < hi:
                    label[k] = (g, f"lib:{why}", "high")
            if k not in label:
                for g, lo, hi, why in ANCHORS:
                    if lo <= k[1] < hi:
                        label[k] = (g, f"block:{why}", "medium")
        elif k[0] == "Default":
            label[k] = ("launcher", "module", "high")
        elif k[0] == "Engine.BuildInfo":
            label[k] = ("crt-libs", "module (build info, CRT)", "high")
        if funcs[k]["kind"] == "rexcrt":
            label[k] = ("crt-libs", "rexcrt", "high")

    # 4. address neighbours (BF.Main), 5. call graph; a few rounds so labels spread into unlabeled stretches
    order = sorted(a for (m, a) in funcs if m == "BF.Main")
    callers = collections.defaultdict(set)
    for k, v in xrefs.items():
        for t in v["calls"] + v["tails"]:
            callers[(k[0], t)].add(k)
    for _ in range(4):
        new = {}
        for i, a in enumerate(order):
            k = ("BF.Main", a)
            if k in label:
                continue
            left = next((label[("BF.Main", order[j])][0] for j in range(i - 1, max(i - 40, -1), -1)
                         if ("BF.Main", order[j]) in label), None)
            right = next((label[("BF.Main", order[j])][0] for j in range(i + 1, min(i + 40, len(order)))
                          if ("BF.Main", order[j]) in label), None)
            if left and left == right:
                new[k] = (left, "addr", "medium")
                continue
            c = collections.Counter()
            v = xrefs.get(k, {"calls": [], "tails": []})
            for t in v["calls"] + v["tails"]:
                if ("BF.Main", t) in label and label[("BF.Main", t)][0] != "crt-libs":
                    c[label[("BF.Main", t)][0]] += 1
            for src in callers[k]:
                if src in label:
                    c[label[src][0]] += 1
            if c:
                g, n = c.most_common(1)[0]
                if n * 2 > sum(c.values()):
                    new[k] = (g, "calls", "low")
                    continue
            if left or right:
                new[k] = (left or right, "addr-near", "low")
        if not new:
            break
        label.update(new)
    return label, vtables


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("coverage", nargs="+")
    ap.add_argument("--typeinfo")
    ap.add_argument("--out", default=os.path.join(ROOT, "docs", "decomp"))
    a = ap.parse_args()
    funcs = load_functions()
    xrefs = load_xrefs()
    hits = load_hits(a.coverage)
    tnames = type_names(a.typeinfo)
    label, vtables = classify(funcs, xrefs, tnames)
    runs = sorted({p.split(":")[0] for s in hits.values() for p in s})

    rows = []
    for k in sorted(hits):
        f = funcs.get(k)
        if not f:
            continue
        g, why, conf = label.get(k, ("unknown", "", "none"))
        hit_runs = sorted({p.split(":")[0] for p in hits[k]})
        phases = sorted({p.split(":")[1] for p in hits[k]}, key=lambda p: PHASE_ORDER.get(p, 99))
        rows.append({**f, "group": g, "why": why, "confidence": conf, "runs": len(hit_runs),
                     "first_phase": phases[0] if phases else "", "phases": phases})
    os.makedirs(a.out, exist_ok=True)
    with open(os.path.join(a.out, "v01_functions.tsv"), "w") as fo:
        fo.write("module\taddress\tsize\tblocks\tname\tgroup\tconfidence\tsignal\truns\tfirst_phase\tphases\n")
        for r in rows:
            fo.write(f"{r['module']}\t0x{r['addr']:08X}\t{r['size']}\t{r['blocks']}\t{r['name']}\t{r['group']}\t"
                     f"{r['confidence']}\t{r['why'][:60]}\t{r['runs']}/{len(runs)}\t{r['first_phase']}\t"
                     f"{len(r['phases'])}\n")
    # summary
    tot = collections.defaultdict(lambda: [0, 0, 0])
    for r in rows:
        t = tot[r["group"]]
        t[0] += 1
        t[1] += r["size"]
        t[2] += r["confidence"] == "high"
    allf = [f for f in funcs.values() if f["kind"] == "code"]
    summary = {
        "runs": runs,
        "functions_total": len(allf),
        "bytes_total": sum(f["size"] for f in allf),
        "hit_functions": len(rows),
        "hit_bytes": sum(r["size"] for r in rows),
        "by_group": {g: {"functions": v[0], "bytes": v[1], "high_confidence": v[2]}
                     for g, v in sorted(tot.items(), key=lambda kv: -kv[1][1])},
        "only_one_run": sum(1 for r in rows if r["runs"] == 1) if len(runs) > 1 else None,
        "vtables": len(vtables), "named_vtables": sum(1 for v in vtables if v[2]),
        "type_names": len(tnames),
    }
    with open(os.path.join(a.out, "v01_summary.json"), "w") as fo:
        json.dump(summary, fo, indent=1)
    print(json.dumps(summary, indent=1))


if __name__ == "__main__":
    main()
