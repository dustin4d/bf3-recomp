def load_functions():
    funcs = {}  # (module, addr) -> dict
    for mod, d in MODULES.items():
        path = os.path.join(ROOT, "project", "generated", d, "bf3_functions.tsv")
        for line in open(path).read().splitlines()[1:]:
            a, size, blocks, name, kind = line.split("\t")
            funcs[(mod, int(a, 16))] = {"module": mod, "addr": int(a, 16), "size": int(size, 16),
                                        "blocks": int(blocks), "name": name, "kind": kind}
    return funcs


def load_xrefs():
    x = {}
    for mod, d in MODULES.items():
        path = os.path.join(ROOT, "logs", "decomp", f"xrefs_{d}.json")
        for a, v in json.load(open(path)).items():
            x[(mod, int(a))] = v
    return x


